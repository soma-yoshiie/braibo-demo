/** 髪の部品。座標は 0..100 の胸像空間。顔は (50,47) 中心の楕円（ry=19）。 */
export interface HairShape {
  d: string;
  /** 刈り上げ（暗く塗る） */
  stub?: boolean;
  /** 重なる円の和集合として外周だけに縁をつける */
  cloud?: boolean;
}
export interface HairDef {
  rx: number; // 顔の横半径
  hw: number; // ハチマキが巻かれる髪の半幅
  back: HairShape[];
  front: HairShape[];
  /** 顔より前に描く細い筋（髪の流れ） */
  lines?: string[];
  /** ハイライトの弧 */
  hl: string;
  /** 髪留め */
  tie?: { x: number; y: number };
}

/** 絶対座標だけの path を左右反転する */
export function mirrorPath(d: string): string {
  let i = 0;
  return d.replace(/([MLCQZ])|(-?\d*\.?\d+)/g, (m, cmd: string | undefined) => {
    if (cmd) { i = 0; return cmd; }
    const v = parseFloat(m);
    const out = i % 2 === 0 ? 100 - v : v;
    i++;
    return String(Math.round(out * 100) / 100);
  });
}
const circles = (cs: [number, number, number][]): string =>
  cs.map(([x, y, r]) => `M${x - r} ${y} a${r} ${r} 0 1 0 ${2 * r} 0 a${r} ${r} 0 1 0 ${-2 * r} 0Z`).join(' ');

